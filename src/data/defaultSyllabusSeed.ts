function stringHash(str: string): string {
  let hash = 5381;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) + hash) + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash).toString(36);
}

/**
 * Transforms raw HSC syllabus array or standard MasterSubject[] into validated, idempotent MasterSubject[]
 */
export function parseAndNormalizeSyllabus(rawInput: unknown): MasterSubject[] {
  if (!Array.isArray(rawInput)) {
    throw new Error('Syllabus JSON must be an array of subject chapters or master subjects.');
  }

  // Case A: Already structured as MasterSubject[]
  const isMasterSubjectArray = rawInput.length > 0 && typeof rawInput[0] === 'object' && rawInput[0] !== null && 'chapters' in rawInput[0];

  if (isMasterSubjectArray) {
    return (rawInput as MasterSubject[]).map((sub, sIdx) => {
      const subMeta = KNOWN_SUBJECTS[sub.name] || {
        id: sub.id || `sub-${stringHash(sub.name)}`,
        code: sub.code || `SUB-${sIdx + 1}`,
        color: sub.color || '#003820',
        order: sub.order || sIdx + 1,
      };

      return {
        id: sub.id || subMeta.id,
        name: sub.name,
        code: sub.code || subMeta.code,
        color: sub.color || subMeta.color,
        order: sub.order || subMeta.order,
        chapters: (sub.chapters || []).map((ch, cIdx) => ({
          id: ch.id || `${sub.id || subMeta.id}-ch-${cIdx + 1}-${stringHash(ch.name)}`,
          name: ch.name,
          order: ch.order || cIdx + 1,
          topics: (ch.topics || []).map((t, tIdx) => ({
            id: t.id || `${sub.id || subMeta.id}-top-${cIdx + 1}-${tIdx + 1}-${stringHash(t.title)}`,
            title: t.title,
            subconcept: t.subconcept || `${ch.name} • Concept synthesis`,
            durationMinutes: t.durationMinutes || 45,
            tag: t.tag || 'Core Syllabus',
            totalWeight: t.totalWeight || 2,
          })),
        })),
      };
    });
  }

  // Case B: Raw HSC JSON array with { subject_name, chapter_name, topics: string[] }
  const rawList = rawInput as RawSyllabusEntry[];
  const subjectMap = new Map<string, {
    name: string;
    chaptersMap: Map<string, string[]>;
  }>();

  for (const item of rawList) {
    if (!item.subject_name || !item.chapter_name) continue;

    if (!subjectMap.has(item.subject_name)) {
      subjectMap.set(item.subject_name, {
        name: item.subject_name,
        chaptersMap: new Map(),
      });
    }

    const subEntry = subjectMap.get(item.subject_name)!;
    if (!subEntry.chaptersMap.has(item.chapter_name)) {
      subEntry.chaptersMap.set(item.chapter_name, []);
    }

    const existingTopics = subEntry.chaptersMap.get(item.chapter_name)!;
    if (Array.isArray(item.topics)) {
      for (const top of item.topics) {
        if (typeof top === 'string' && top.trim().length > 0) {
          existingTopics.push(top.trim());
        }
      }
    }
  }

  const result: MasterSubject[] = [];
  let sIndex = 1;

  for (const [subjectName, subData] of subjectMap.entries()) {
    const meta = KNOWN_SUBJECTS[subjectName] || {
      id: `sub-${stringHash(subjectName)}`,
      code: `HSC-${sIndex}`,
      color: '#003820',
      order: sIndex,
    };

    const chapters: MasterSubject['chapters'] = [];
    let cIndex = 1;

    for (const [chapterName, topicTitles] of subData.chaptersMap.entries()) {
      const chapterId = `${meta.id}-ch-${cIndex}-${stringHash(chapterName)}`;
      const topics = topicTitles.map((tTitle, tIndex) => ({
        id: `${meta.id}-top-${cIndex}-${tIndex + 1}-${stringHash(tTitle)}`,
        title: tTitle,
        subconcept: `${chapterName} • HSC Curriculum Core`,
        durationMinutes: 45,
        tag: 'Core Concept',
        totalWeight: 2,
      }));

      chapters.push({
        id: chapterId,
        name: chapterName,
        order: cIndex,
        topics,
      });

      cIndex++;
    }

    result.push({
      id: meta.id,
      name: subjectName,
      code: meta.code,
      color: meta.color,
      order: meta.order || sIndex,
      chapters,
    });

    sIndex++;
  }

  return result.sort((a, b) => a.order - b.order);
}

export const DEFAULT_HSC_SYLLABUS: MasterSubject[] = parseAndNormalizeSyllabus(RAW_HSC_SYLLABUS_JSON);
